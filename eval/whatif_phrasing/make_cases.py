"""Writes eval/whatif_phrasing/cases.jsonl: What If messages as people type them, each with a household from
app/data/sample_households.json and the expected outcome.

Expected outcome: "refuse" (a safety path answers before any reading), "clarify" (nothing the plan can model, or out of
range: the reply asks or explains, with chips), or a dict of what the What If changes, in plain terms:

  retire_age, partner_retire_age, claim_age          the new age
  spending_goal                                       the new yearly spending goal ($)
  spend_now_less                                      $ a year less spent now and saved
  save_more_per_year                                  $ a year more saved (negative: less)
  save_rate                                           the share of pay saved in all
  part_time                                           {"per_year": $, "until_age": age or None}
  state                                               two-letter code
  children_added                                      how many children are added
  college                                             [[child index, "public"|"private"|"none", share paid]]
  pets                                                {kind: count after the change} for each kind that changes
  pay_off                                             debt words: credit_card, student, car, mortgage, all, high, other
  shock                                               "fall:<pct>:now|retirement", "inflation", "bad_decade"
  risk                                                careful, balanced or growth
  emergency_months, insurance, downsize, match_full   as in the change dict

Run:  python eval/whatif_phrasing/make_cases.py
"""
